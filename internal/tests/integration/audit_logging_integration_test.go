// TestPasswordChangeServiceAuditIntegration tests the actual integration
// between password change service and audit logging
func TestPasswordChangeServiceAuditIntegration(t *testing.T) {
	t.Parallel()

	// Create mock dependencies
	passwordChangeRepo := mocks.NewMockPasswordChangeRepository()
	passwordHistoryRepo := mocks.NewMockPasswordHistoryRepository()
	forgotPasswordRepo := mocks.NewMockForgotPasswordRepository()
	userRepo := mocks.NewMockUserRepository()
	passwordService := mocks.NewMockPasswordService()
	otpService := mocks.NewMockOTPService()
	sessionRepo := mocks.NewMockSessionRepository()

	// Create audit service with event capture
	auditRepo := mocks.NewMockAuditRepository()
	var capturedAuditEvents []*domain.ComprehensiveAuditEvent
	
	auditRepo.CreateFunc = func(ctx context.Context, event *domain.ComprehensiveAuditEvent) error {
		// Set correlation ID like the real repository would
		if event.CorrelationID == uuid.Nil {
			event.SetCorrelationID()
		}
		capturedAuditEvents = append(capturedAuditEvents, event)
		return nil
	}

	auditService := services.NewComprehensiveAuditService(
		auditRepo, nil, nil, nil, nil, nil,
		nil, // config
		nil, // logger
	)

	// Create password change service with audit integration
	config := services.DefaultPasswordChangeConfig()
	passwordChangeService := services.NewPasswordChangeService(
		passwordChangeRepo,
		passwordHistoryRepo,
		forgotPasswordRepo,
		userRepo,
		passwordService,
		otpService,
		sessionRepo,
		auditService,
		config,
	)

	// Test: Password change initiation with audit logging
	t.Run("password_change_initiation_with_audit", func(t *testing.T) {
		// Setup mocks for successful initiation
		userRepo.FindByIDFunc = func(ctx context.Context, id uint) (*domain.User, error) {
			return &domain.User{
				ID:           1,
				Email:        "user@example.com",
				PasswordHash: "old_hash",
				IsActive:     true,
			}, nil
		}

		passwordService.VerifyFunc = func(hashedPassword, password string) bool {
			// Return true only for the current password verification
			return hashedPassword == "old_hash" && password == "current_password"
		}

		passwordService.HashFunc = func(password string) (string, error) {
			return "new_hashed_password", nil
		}

		passwordHistoryRepo.GetRecentPasswordsFunc = func(ctx context.Context, userID uint, count int) ([]string, error) {
			return []string{"different_old_hash"}, nil // No password reuse
		}

		passwordChangeRepo.GetActiveByUserIDFunc = func(ctx context.Context, userID uint) (*domain.PasswordChangeRequest, error) {
			return nil, nil // No active request
		}

		passwordChangeRepo.CountRecentByUserIDFunc = func(ctx context.Context, userID uint, since time.Time) (int64, error) {
			return 0, nil // Within rate limit
		}

		passwordChangeRepo.CreateFunc = func(ctx context.Context, request *domain.PasswordChangeRequest) error {
			return nil // Request created successfully
		}

		otpService.GenerateFunc = func(ctx context.Context, phone string, userID uint) (*domain.OTPRequest, error) {
			return &domain.OTPRequest{
				Phone: phone,
				Code:  "123456",
			}, nil
		}

		// Execute password change initiation
		response, err := passwordChangeService.InitiatePasswordChange(
			context.Background(),
			1,                      // userID
			"current_password",     // currentPassword
			"NewPassword123!@#",    // newPassword (stronger password)
			"NewPassword123!@#",    // confirmPassword
			"192.168.1.100",       // ipAddress
			"Integration-Test/1.0", // userAgent
		)

		// Verify operation succeeded
		if err != nil {
			t.Fatalf("Password change initiation failed: %v", err)
		}

		if response == nil {
			t.Fatal("Expected response, got nil")
		}

		if response.Status != "initiated" {
			t.Errorf("Expected status 'initiated', got %s", response.Status)
		}

		// Verify audit event was logged
		if len(capturedAuditEvents) != 1 {
			t.Fatalf("Expected 1 audit event, got %d", len(capturedAuditEvents))
		}

		auditEvent := capturedAuditEvents[0]
		if auditEvent.EventType != domain.EventTypePasswordChangeInitiated {
			t.Errorf("Expected audit event type %s, got %s", 
				domain.EventTypePasswordChangeInitiated, auditEvent.EventType)
		}

		if auditEvent.UserID == nil || *auditEvent.UserID != 1 {
			t.Errorf("Expected audit user ID 1, got %v", auditEvent.UserID)
		}

		if auditEvent.IPAddress != "192.168.1.100" {
			t.Errorf("Expected audit IP address '192.168.1.100', got %s", auditEvent.IPAddress)
		}

		if auditEvent.UserAgent != "Integration-Test/1.0" {
			t.Errorf("Expected audit user agent 'Integration-Test/1.0', got %s", auditEvent.UserAgent)
		}

		t.Logf("✅ Password change service audit integration verified successfully")
		t.Logf("📝 Audit event captured: %s", auditEvent.EventType)
		t.Logf("🔐 User ID: %d, IP: %s", *auditEvent.UserID, auditEvent.IPAddress)
	})

	t.Logf("🎉 PASSWORD CHANGE SERVICE AUDIT INTEGRATION VERIFIED")
	t.Logf("✅ End-to-end audit logging is working correctly")
}