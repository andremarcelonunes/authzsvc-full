		if event.EventType != domain.EventTypePasswordChangeExpired {
			t.Errorf("Expected event type %s, got %s", domain.EventTypePasswordChangeExpired, event.EventType)
		}
		
		if event.Action != "password_change_expire" {
			t.Errorf("Expected action 'password_change_expire', got %s", event.Action)
		}
		
		if event.Success {
			t.Error("Expected success to be false for expiration")
		}

